import { z } from 'zod';
import { ActuationKindSchema, type ActuationKind } from './capability.js';
import { ContextKindSchema, SurfaceSchema, type Surface } from './context.js';

/**
 * Capability registry: non-authorizing metadata for promoting host APIs into the product.
 *
 * The registry is deliberately descriptive. It can teach the skill/UI how to discover and use a
 * capability, but it never makes a write executable. A write is executable only when the active
 * bridge advertises the exact ActuationKind in its live CapabilityManifest.
 */

export const CapabilityPromotionStatusSchema = z.enum([
  'implemented',
  'promotable',
  'catalog-only',
  'estate-gated',
  'blocked-host-api',
]);
export type CapabilityPromotionStatus = z.infer<typeof CapabilityPromotionStatusSchema>;

export const CapabilityExposureSchema = z.enum([
  'core-verb',
  'specialized',
  'context-only',
  'estate',
]);
export type CapabilityExposure = z.infer<typeof CapabilityExposureSchema>;

export const CapabilityPrioritySchema = z.enum(['p0', 'p1', 'p2', 'p3']);
export type CapabilityPriority = z.infer<typeof CapabilityPrioritySchema>;

export const RequirementSetSchema = z.object({
  name: z.string(),
  minVersion: z.string(),
  notes: z.string().optional(),
});
export type RequirementSet = z.infer<typeof RequirementSetSchema>;

export const CapabilityRegistryEntrySchema = z.object({
  kind: ActuationKindSchema,
  surface: SurfaceSchema,
  status: CapabilityPromotionStatusSchema,
  exposure: CapabilityExposureSchema,
  priority: CapabilityPrioritySchema,
  command: z.string(),
  title: z.string(),
  useWhen: z.string(),
  hostApis: z.array(z.string()),
  requirementSets: z.array(RequirementSetSchema),
  contextKinds: z.array(ContextKindSchema),
  discovery: z.array(z.string()),
  sequence: z.array(z.string()),
  examples: z.array(z.string()).default([]),
  preview: z.array(z.string()),
  inverse: z.string(),
  provenance: z.string(),
  failureModes: z.array(z.string()),
  skillRefs: z.array(z.string()).default([]),
});
export type CapabilityRegistryEntry = z.infer<typeof CapabilityRegistryEntrySchema>;

