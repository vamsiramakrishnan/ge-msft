// ADR-0008 §4 — emit the versioned language manifest from the authoritative @ge/contracts
// definitions into a committed JSON the skill's Python preflight loads. Run after building
// contracts (`bun run typecheck` / `tsc -b` produces dist/). Re-running must produce NO diff —
// a byte change is a real language change (CI diffs the committed file as the drift gate).
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildLanguageManifest, assertManifestConsistent } from '../dist/language-manifest.js';

const manifest = assertManifestConsistent(buildLanguageManifest());
const json = JSON.stringify(manifest, null, 2) + '\n';
const check = process.argv.includes('--check');
const changed = [];

const here = dirname(fileURLToPath(import.meta.url));
const targets = [
  // Bundled into the skill package so the Python sandbox loads it (no hand-maintained tables).
  resolve(here, '../../../skill/m365-surface-commander/scripts/m365-cli-1.0.json'),
];
for (const out of targets) {
  writeOrCheck(out, json);
  if (!check)
    console.log(`wrote ${out} (${manifest.version}, ${manifest.verbs.write.length} write verbs)`);
}

const generatedDocs = [
  [
    resolve(here, '../../../skill/m365-surface-commander/references/generated-capability-catalog.md'),
    renderCapabilityCatalog(manifest),
  ],
  [
    resolve(here, '../../../skill/m365-surface-commander/references/generated-command-catalog.md'),
    renderCommandCatalog(manifest),
  ],
];
for (const [out, text] of generatedDocs) {
  writeOrCheck(out, text);
  if (!check) console.log(`wrote ${out}`);
}
if (check) {
  if (changed.length > 0) {
    console.error('language/skill artifacts are out of date:');
    for (const out of changed) console.error(`  ${out}`);
    process.exit(1);
  }
  console.log('language/skill artifacts are current');
}

function writeOrCheck(out, text) {
  if (check) {
    const current = existsSync(out) ? readFileSync(out, 'utf8') : undefined;
    if (current !== text) changed.push(out);
    return;
  }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
}

function renderCapabilityCatalog(m) {
  const entries = [...m.capabilityRegistry].sort((a, b) =>
    `${a.surface}:${a.status}:${a.kind}`.localeCompare(`${b.surface}:${b.status}:${b.kind}`),
  );
  const lines = [
    '---',
    'title: Generated Capability Catalog',
    'kind: generated-reference',
    'skill: m365-surface-commander',
    'topics: [generated, capabilities, registry, office-js]',
    'load_when: Checking generated capability metadata, registry status, requirement sets, or capability-specific playbooks.',
    '---',
    '',
    '# Generated capability catalog',
    '',
    '<!-- GENERATED by bun run emit:language. Do not edit by hand. -->',
    '',
    'This file is generated from `packages/contracts/src/capability-registry.ts`. Registry metadata is **not** write authority; a capability is executable only when the live bridge manifest advertises the same actuation kind for the active surface.',
    '',
    '| Surface | Status | Command | Kind | Title | Requirement sets | Use when |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const e of entries) {
    lines.push(
      `| ${cell(e.surface)} | ${cell(e.status)} | \`${cell(e.command)}\` | \`${cell(e.kind)}\` | ${cell(e.title)} | ${cell(formatRequirementSets(e.requirementSets))} | ${cell(e.useWhen)} |`,
    );
  }
  lines.push('');
  lines.push('## Implemented live capabilities');
  lines.push('');
  for (const surface of [...new Set(entries.map((e) => e.surface))].sort()) {
    const kinds = entries
      .filter((e) => e.surface === surface && e.status === 'implemented')
      .map((e) => `\`${e.kind}\``);
    lines.push(`- **${surface}:** ${kinds.length ? kinds.join(', ') : 'none'}`);
  }
  lines.push('');
  return lines.join('\n');
}

function renderCommandCatalog(m) {
  const lines = [
    '---',
    'title: Generated Command Catalog',
    'kind: generated-reference',
    'skill: m365-surface-commander',
    'topics: [generated, commands, cli, help]',
    'load_when: Checking generated command syntax, command playbooks, or the CLI help surface.',
    '---',
    '',
    '# Generated command catalog',
    '',
    '<!-- GENERATED by bun run emit:language. Do not edit by hand. -->',
    '',
    `Language version: \`${m.version}\``,
    '',
    '## Core verbs',
    '',
    `- Read: ${m.verbs.read.map((v) => `\`${v}\``).join(', ')}`,
    `- Write: ${m.verbs.write.map((v) => `\`${v}\``).join(', ')}`,
    `- Control: ${m.verbs.control.map((v) => `\`${v}\``).join(', ')}`,
    '',
    '## Write verb mapping',
    '',
    '| Verb | Actuation kind |',
    '| --- | --- |',
  ];
  for (const [verb, kind] of Object.entries(m.writeVerbToKind).sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    lines.push(`| \`${cell(verb)}\` | \`${cell(kind)}\` |`);
  }
  lines.push('');
  lines.push('## Specialized slash surface');
  lines.push('');
  lines.push(
    'These actuation kinds are reached as `/<kind> key=value ...` only when the live turn advertises them.',
  );
  lines.push('');
  for (const chunk of chunks(m.specializedKinds, 6)) {
    lines.push(`- ${chunk.map((kind) => `\`/${kind}\``).join(', ')}`);
  }
  lines.push('');
  return lines.join('\n');
}

function formatRequirementSets(sets) {
  if (!sets.length) return '-';
  return sets.map((set) => `${set.name} ${set.minVersion}${set.notes ? ` (${set.notes})` : ''}`).join('; ');
}

function chunks(items, size) {
  const out = [];
  for (let i = 0; i < items.length; i += size) out.push(items.slice(i, i + size));
  return out;
}

function cell(value) {
  return String(value ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ')
    .trim();
}
