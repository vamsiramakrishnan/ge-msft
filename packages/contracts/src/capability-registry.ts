export function capabilityRegistryEntries(): CapabilityRegistryEntry[] {
  return [...CAPABILITY_REGISTRY];
}

export function registryEntryForKind(kind: ActuationKind): CapabilityRegistryEntry | undefined {
  return CAPABILITY_REGISTRY.find((entry) => entry.kind === kind);
}

export function registryEntryForKindAndSurface(
  kind: ActuationKind,
  surface: Surface,
): CapabilityRegistryEntry | undefined {
  return CAPABILITY_REGISTRY.find((entry) => entry.kind === kind && entry.surface === surface);
}

export function registryEntriesForSurface(surface: Surface): CapabilityRegistryEntry[] {
  return CAPABILITY_REGISTRY.filter((entry) => entry.surface === surface);
}

export function implementedRegistryEntriesForSurface(surface: Surface): CapabilityRegistryEntry[] {
  return registryEntriesForSurface(surface).filter((entry) => entry.status === 'implemented');
}

export function implementedRegistryKindsForSurface(surface: Surface): ActuationKind[] {
  return implementedRegistryEntriesForSurface(surface).map((entry) => entry.kind);
}

export function assertCapabilityRegistryConsistent(
  entries: readonly CapabilityRegistryEntry[] = CAPABILITY_REGISTRY,
): CapabilityRegistryEntry[] {
  const parsed = entries.map((entry) => CapabilityRegistryEntrySchema.parse(entry));
  const seen = new Set<string>();
  const errors: string[] = [];
  for (const entry of parsed) {
    const key = `${entry.surface}:${entry.kind}`;
    if (seen.has(key)) errors.push(`duplicate capability registry entry "${key}"`);
    seen.add(key);
    if (entry.exposure === 'core-verb' && entry.command.startsWith('/')) {
      errors.push(`${key} is core-verb but uses slash command ${entry.command}`);
    }
    if (entry.exposure === 'specialized' && !entry.command.startsWith('/')) {
      errors.push(`${key} is specialized but command is not slash-prefixed`);
    }
    if (entry.status === 'implemented' && entry.priority !== 'p0') {
      errors.push(`${key} is implemented but not p0`);
    }
  }
  if (errors.length > 0) {
    throw new Error(`capability registry is inconsistent:\n  - ${errors.join('\n  - ')}`);
  }
  return parsed;
}

function entry(input: CapabilityRegistryEntry): CapabilityRegistryEntry {
  return CapabilityRegistryEntrySchema.parse(input);
}
